#!/usr/bin/env python3
"""Print the real numbers you need for the write-up and the demo, read from files and git. Nothing is typed by hand.

  python scripts/evidence.py            print to the screen
  python scripts/evidence.py --write    also save docs/evidence.md

Sources: git log, target/surefire-reports, PIT mutations.xml (target/pit-reports and pit-before),
docs/review/findings.json, docs/ai-log/ai-log.jsonl. A missing source is reported as "not found", never invented.
Playwright results are not collected: read the "passed" line from `npx playwright test`.
"""
import collections, glob, json, os, subprocess, sys
sys.dont_write_bytecode = True
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ai_log  # noqa: E402


def git(*args):
    try:
        out = subprocess.run(["git", *args], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, timeout=20)
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:
        return ""


def pit_score(folder):
    """Score from the newest mutations.xml under folder. detected / all mutants except non-viable ones."""
    files = glob.glob(os.path.join(folder, "**", "mutations.xml"), recursive=True)
    if not files:
        return None
    newest = max(files, key=os.path.getmtime)
    counts = collections.Counter()
    for node in ET.parse(newest).getroot().iter("mutation"):
        counts[node.get("status", "UNKNOWN")] += 1
    detected = counts["KILLED"] + counts["TIMED_OUT"] + counts["MEMORY_ERROR"]
    total = sum(counts.values()) - counts["NON_VIABLE"]
    if total == 0:
        return None
    return {"file": newest, "total": total, "detected": detected, "survived": counts["SURVIVED"],
            "no_coverage": counts["NO_COVERAGE"], "percent": round(100.0 * detected / total, 1)}


def section(title, lines):
    return ["", f"## {title}", ""] + lines


def build():
    out = ["# Evidence (generated by scripts/evidence.py)", "",
           "Every number below is read from a file or from git. Check it against the tool's own report before you quote it."]

    commits = git("log", "--format=%h %s", "--reverse").splitlines()
    out += section("Commits (oldest first)", [f"- {c}" for c in commits] or ["- not a git repository"])
    out.append(f"\nTotal: {len(commits)}")

    tests = ai_log.test_evidence()
    out += section("Unit tests (Maven surefire report)", [
        f"- {tests['passed']} passed of {tests['tests']}; {tests['failed']} failed, {tests['errors']} errors, {tests['skipped']} skipped (report time {tests['report_time']})"
        if tests else "- not found. Run `mvn test` first."])

    lines = []
    for label, folder in (("Before", "pit-before"), ("After (latest)", os.path.join("target", "pit-reports"))):
        s = pit_score(folder)
        lines.append(f"- {label}: {s['detected']} of {s['total']} mutants killed = {s['percent']} percent "
                     f"({s['survived']} survived, {s['no_coverage']} not covered). File: {s['file']}" if s
                     else f"- {label}: not found in `{folder}`. Run PIT (prompt 4).")
    lines.append("- Formula: detected / all mutants except non-viable ones. The PIT HTML report is authoritative; if it differs, quote the report.")
    out += section("Mutation testing (PIT)", lines)

    path = os.path.join("docs", "review", "findings.json")
    if os.path.exists(path):
        findings = json.load(open(path, encoding="utf-8"))
        tally = collections.Counter(f["verdict"] for f in findings)
        out += section("Review findings", [f"- Total: {len(findings)}; fixed {tally['fixed']}, dismissed {tally['dismissed']}, deferred {tally['deferred']}, pending {tally['pending']}"]
                       + [f"- {f['id']} [{f['severity']}] **{f['verdict']}**: {f['title']} ({f['verdict_reason'][:90]})" for f in findings])
    else:
        out += section("Review findings", ["- not found. Run prompt 6."])

    rows = ai_log.read_log()
    manual = [r for r in rows if r.get("source") != "git-hook"]
    if manual:
        corr = [c for r in manual for c in r["human_intervention"]["corrections"]]
        out += section("AI log", [
            f"- Entries: {len(manual)} AI interactions, {len(rows) - len(manual)} commit records",
            "- Tools / models: " + ", ".join(sorted({f"{r['ai_tool']} / {r['model']}" for r in manual})),
            "- Modes: " + ", ".join(sorted({r["mode"] for r in manual})),
            f"- Entries with human intervention: {sum(1 for r in manual if any(r['human_intervention'].values()))} of {len(manual)}",
            "- Outcomes: " + ", ".join(f"{k} x{v}" for k, v in collections.Counter(r["outcome"] for r in manual).items()),
            "- Skills / sub-agents / MCP actually used: " + (", ".join(sorted({x['name'] for r in manual for x in r['skills_used'] + r['subagents_used']} | {m['tool'] for r in manual for m in r['mcp_tools_used']})) or "none"),
        ] + ([f"- Correction you made: {c}" for c in corr] or ["- No corrections recorded yet. Add them with `annotate last --human-correction`."]))
    else:
        out += section("AI log", ["- no entries yet"])

    checks = []
    def run(label, *cmd):
        r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        checks.append(f"- {label}: {'OK' if r.returncode == 0 else 'FAILED'}" + ("" if r.returncode == 0 else f" ({r.stdout.strip().splitlines()[-1][:100] if r.stdout.strip() else ''})"))
    py = sys.executable
    run("prompt linter", py, "-B", "scripts/check_prompts.py")
    run("AI log validate", py, "-B", "scripts/ai_log.py", "validate")
    if os.path.exists(path):
        run("findings validator (all verdicts set)", py, "-B", "scripts/hooks/validate-findings.py", "--final", path)
    out += section("Checks", checks)
    return "\n".join(out) + "\n"


def main():
    text = build()
    print(text)
    if "--write" in sys.argv:
        with open(os.path.join("docs", "evidence.md"), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("saved docs/evidence.md")


if __name__ == "__main__":
    main()
